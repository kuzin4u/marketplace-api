-- ============================================================
-- СПРИНТ 0 · Миграция 05 · Идемпотентность создания заказа
--
-- Повторная отправка формы, обрыв связи после записи, но до ответа,
-- повторный клик по «Оформить» — всё это создаёт второй заказ на те же
-- товары. Клиент видит один заказ, база хранит два, остатки списаны
-- дважды.
--
-- Задача 0.8 требует намеренно вызывать редкие пути при двухнедельном
-- наблюдении, и повторная отправка формы — первый в списке. Без ключа
-- идемпотентности эта проверка гарантированно даёт расхождение.
--
-- Клиент передаёт заголовок Idempotency-Key; повторный запрос с тем же
-- ключом возвращает ранее созданный заказ, а не создаёт новый.
--
-- ПРИМЕНЯЕТСЯ ПОСЛЕ 04.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f schema/05_idempotency.sql
-- ============================================================

BEGIN;

ALTER TABLE orders ADD COLUMN IF NOT EXISTS idempotency_key TEXT;

-- Частичный индекс: ограничение действует только для заказов с ключом.
-- Заказы без ключа (перенесённая история, ручное создание) не мешают.
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_idempotency
    ON orders (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

COMMENT ON COLUMN orders.idempotency_key IS
    'Значение заголовка Idempotency-Key. Повторный запрос с тем же ключом возвращает существующий заказ.';

COMMIT;
