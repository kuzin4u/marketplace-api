-- ============================================================
-- Миграция 08 · Лишний индекс на seller_auth
--
-- В боевой базе нашёлся idx_seller_auth_seller_id — обычный индекс
-- по seller_id, заведённый вручную до того, как таблица попала
-- в схему. Уникальный uq_seller_auth_seller из миграции 07 полностью
-- его перекрывает: он тоже индекс по тому же столбцу и обслуживает
-- те же запросы, вдобавок давая гарантию.
--
-- Два индекса по одному столбцу — это удвоенная запись при каждой
-- выдаче учётки и лишняя строка при разборе плана. Вреда мало,
-- смысла — никакого.
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ПРАВКОЙ 07
--
-- 07 уже прогнана на боевой базе. Дописать в неё DROP означало бы,
-- что файл в репозитории больше не совпадает с тем, что реально
-- выполнено. Именно это расхождение и вышло боком с миграциями
-- 04–06, поэтому применённые файлы не правятся.
--
-- ПРИМЕНЯЕТСЯ ПОСЛЕ 07. Независима от 04, 05, 06.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f schema/08_drop_redundant_index.sql
--
-- Повторный запуск безопасен.
-- ============================================================

BEGIN;

-- Снимаем лишний только убедившись, что уникальный на месте. Иначе
-- при запуске 08 без 07 таблица осталась бы вообще без индекса
-- по seller_id — и без гарантии, и без ускорения.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relkind = 'i'
          AND c.relname = 'uq_seller_auth_seller'
    ) THEN
        RAISE EXCEPTION 'Сначала примените 07: uq_seller_auth_seller отсутствует, снимать замену нечем.';
    END IF;
END $$;

DROP INDEX IF EXISTS idx_seller_auth_seller_id;

COMMIT;

