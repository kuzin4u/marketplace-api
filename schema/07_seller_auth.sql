-- ============================================================
-- Миграция 07 · Учётные записи продавцов
--
-- Таблица seller_auth до сих пор существовала только в рантайме:
-- её создавал CREATE TABLE IF NOT EXISTS при старте auth-seller.js.
-- Это работало, но означало, что определение таблицы, хранящей хэши
-- паролей, нельзя прочитать, не читая код, и нельзя воспроизвести
-- на пустой базе иначе как запуском приложения.
--
-- Здесь определение переносится в схему. Создание из кода НЕ убирается:
-- порядок применения мигрaций и порядок деплоя не связаны, и модуль
-- должен подниматься на базе, где 07 ещё не прогоняли.
--
-- Главное изменение — уникальность seller_id.
--
-- В коде проверка «у участника уже есть учётка» делалась двумя
-- запросами: SELECT, затем INSERT. Между ними есть окно: два
-- одновременных запроса оба видят пусто и оба вставляют. Итог —
-- второй вход к тому же продавцу, причём первый не отобран.
-- Проверку в коде оставляем ради внятного ответа 409, но
-- гарантию даёт индекс, а не она.
--
-- ПРИМЕНЯЕТСЯ НЕЗАВИСИМО от 04, 05, 06: затрагивает только
-- seller_auth и participants(id), которые есть уже после 01.
-- На боевой базе (состояние 01+03) применима как есть.
--
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f schema/07_seller_auth.sql
--
-- Повторный запуск безопасен.
-- ============================================================

BEGIN;

-- ============================================================
-- 0. ПРЕДПОЛЁТНАЯ ПРОВЕРКА
--
-- Уникальный индекс не встанет, если у кого-то уже две учётки.
-- Обычный CREATE INDEX сообщил бы про одну конфликтующую пару;
-- этот блок показывает всех сразу и называет действие.
-- ============================================================
DO $$
DECLARE
    dup TEXT := '';
    r   RECORD;
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = 'public' AND table_name = 'seller_auth') THEN
        FOR r IN
            SELECT seller_id, count(*) AS n, string_agg(login, ', ' ORDER BY created_at) AS logins
            FROM seller_auth GROUP BY seller_id HAVING count(*) > 1
        LOOP
            dup := dup || format(E'\n  - %s: %s учётки (%s)', r.seller_id, r.n, r.logins);
        END LOOP;

        IF dup <> '' THEN
            RAISE EXCEPTION E'Миграция остановлена: у продавцов больше одной учётной записи.%\n\nРешите, какая из них действующая, лишние удалите, повторите. Удаление учётки не удаляет участника из реестра.', dup;
        END IF;
    END IF;

    RAISE NOTICE 'Предполётная проверка пройдена.';
END $$;

-- ============================================================
-- 1. ТАБЛИЦА
--
-- Определение дословно повторяет то, что создаёт auth-seller.js.
-- Если правится одно — правится и второе, иначе на разных базах
-- окажутся разные таблицы с одним именем.
--
-- Пароль хранится хэшем bcrypt (cost 10), выдаётся в auth-seller.js.
-- Открытый пароль в базу не попадает и не логируется.
-- ============================================================
CREATE TABLE IF NOT EXISTS seller_auth (
    login         TEXT PRIMARY KEY,
    seller_id     TEXT NOT NULL REFERENCES participants(id),
    password_hash TEXT NOT NULL,
    created_at    TIMESTAMPTZ DEFAULT now(),
    last_login    TIMESTAMPTZ
);

COMMENT ON TABLE seller_auth IS
    'Учётные данные продавца. Выдаёт Организатор через POST /api/v1/auth/register с ключом допуска (ст. 16). Регистрация самим продавцом невозможна.';

-- ============================================================
-- 2. ОДНА УЧЁТКА НА УЧАСТНИКА
--
-- Ради чего миграция и написана. seller_id внутри токена определяет,
-- чьи товары, заказы и выплаты видны; вторая учётка к тому же
-- продавцу — второй ключ от того же сейфа, о котором владелец
-- первого ключа не знает.
--
-- Отзыв доступа — удаление строки, а не заведение новой.
-- ============================================================
CREATE UNIQUE INDEX IF NOT EXISTS uq_seller_auth_seller
    ON seller_auth (seller_id);

COMMENT ON INDEX uq_seller_auth_seller IS
    'Одна учётная запись на участника. Проверка в auth-seller.js даёт понятный 409, гарантию даёт этот индекс: между SELECT и INSERT есть окно гонки.';

-- Поиск по продавцу отдельным индексом не нужен: уникальный
-- сам по себе индекс и обслуживает такие запросы.

COMMIT;

